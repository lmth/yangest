//! Build script: auto-generate `extern crate` declarations for all
//! `yangest-plugin-*` dependencies so that `main.rs` never needs to name them.
//!
//! Each plugin crate self-registers via `inventory::submit!`; the linker only
//! includes their object files if they appear in the link graph.  The generated
//! `plugin_externs.rs` (included by `main.rs`) provides that reference.

use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").unwrap();
    let cargo_toml =
        fs::read_to_string(format!("{}/Cargo.toml", manifest_dir)).unwrap();

    let mut externs = String::from("// Auto-generated by build.rs — do not edit.\n");
    let mut in_deps = false;

    for line in cargo_toml.lines() {
        let trimmed = line.trim();
        if trimmed == "[dependencies]" {
            in_deps = true;
            continue;
        }
        if trimmed.starts_with('[') {
            in_deps = false;
            continue;
        }
        if in_deps {
            if let Some(name) = trimmed.split('=').next() {
                let name = name.trim().trim_matches('"');
                if name.starts_with("yangest-plugin-") {
                    let ident = name.replace('-', "_");
                    externs.push_str(&format!("extern crate {};\n", ident));
                }
            }
        }
    }

    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    fs::write(out.join("plugin_externs.rs"), externs).unwrap();

    println!("cargo:rerun-if-changed=Cargo.toml");
}
